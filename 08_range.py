# RANGE 

# range(stop)
# Starts at 0 and stops before the number

for i in range(5):
    print(i)

# Output:
# 0
# 1
# 2
# 3
# 4


# range(start, stop)

for i in range(1, 6):
    print(i)

# Output:
# 1
# 2
# 3
# 4
# 5


# range(start, stop, step)

for i in range(0, 11, 2):
    print(i)

# Output:
# 0
# 2
# 4
# 6
# 8
# 10


# Important Note:
# The stop value is NOT included!! 