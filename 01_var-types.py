# VARIABLE TYPES

age = 18              # int = whole number without decimals
gpa = 3.93          # float = number with decimals
name = "Frankie"      # str = text/string data inside quotation marks
isStudent = True      # bool = Boolean value (True or False)

# Variables store information in memory
# The variable name goes on the left side of =
# The value being stored goes on the right side of =

# Python automatically determines the variable type
# This process is called dynamic typing

print(type(age))         
print(type(gpa))         
print(type(name))        
print(type(isStudent))