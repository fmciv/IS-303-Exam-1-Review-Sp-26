
# SELECTION 

# Selection uses if, elif, and else

grade = 84

if grade >= 90:
    print("A")

elif grade >= 80:
    print("B")

elif grade >= 70:
    print("C")

else:
    print("Needs Improvement")


# Using and

age = 19
gpa = 3.8

if age >= 18 and gpa >= 3.5:
    print("Scholarship Eligible")


# Using or

major = "IS"

if major == "IS" or major == "CS":
    print("Technology Major")