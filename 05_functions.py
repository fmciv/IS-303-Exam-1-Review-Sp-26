# FUNCTIONS 

# Functions allow you to reuse code without rewriting it

# Function using print()
# print() only displays the result

def addPrint(num):
    print(num + 2) 

result1 = addPrint(5)

print(result1)


# Function using return
# return sends the value back

def addReturn(num):
    return num + 2

result2 = addReturn(5)

print(result2)   # outputs: 7


