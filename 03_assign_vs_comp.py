# ASSIGNMENT (=)

# Stores a value inside a variable

x = 5          # assign/store the value 5 into x
name = "Bob"   # assign/store text into name

print(x)       # prints 5


# COMPARISON (==)

# Checks if two values are equal

print(x == 5)      # True because x IS equal to 5
print(x == 10)     # False because x is NOT equal to 10


# Common use inside an if statement

if x == 5:
    print("x equals 5")


# VERY IMPORTANT:
# =  means ASSIGN a value
# == means COMPARE two values